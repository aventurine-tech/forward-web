# Usage: python3 scripts/build-logo.py -60 -40 src/data/logo.ts  (needs fonttools and Inter SemiBold)
# Builds the Forward International logo as SVG paths, traced to the 1720x422 reference.
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

FONT = '/usr/share/fonts/opentype/inter/Inter-SemiBold.otf'
font = TTFont(FONT)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
kern = {}

def line(text, x0, x1, top, bottom, tracking=0):
    # layout in font units
    xs, x = [], 0
    for ch in text:
        g = cmap[ord(ch)]
        xs.append((g, x))
        x += gs[g].width + tracking
    # ink bounds
    bp = BoundsPen(gs)
    for g, ox in xs:
        tp = TransformPen(bp, (1, 0, 0, 1, ox, 0))
        gs[g].draw(tp)
    xmin, ymin, xmax, ymax = bp.bounds
    sy = (bottom - top) / (ymax - ymin)
    sx = (x1 - x0) / (xmax - xmin)
    pen = SVGPathPen(gs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
    for g, ox in xs:
        # font y up -> svg y down
        t = (sx, 0, 0, -sy, x0 - xmin * sx + ox * sx, top + ymax * sy)
        gs[g].draw(TransformPen(pen, t))
    return pen.getCommands(), sx / sy

fw, r1 = line('FORWARD', 466, 1718, 54, 256, tracking=float(sys.argv[1]) if len(sys.argv) > 1 else 0)
it, r2 = line('INTERNATIONAL', 466, 1718, 295, 419, tracking=float(sys.argv[2]) if len(sys.argv) > 2 else 0)
print('stretch', r1, r2, file=sys.stderr)
c1 = [(81,136),(147,136),(222,212.5),(147,289),(81,289),(156,212.5)]
c2 = [(x+129,y) for x,y in c1]
poly = lambda pts: 'M' + 'L'.join('%g %g' % p for p in pts) + 'Z'
mark = 'M0 0H419V422H0Z' + poly(c1) + poly(c2)
open(sys.argv[3] if len(sys.argv) > 3 else '/dev/stdout', 'w').write(
f"""// Forward International logo, redrawn as vectors from the 1720x422 logo file
// (design/reference/logo-amcham.jpg): a blue square with two white chevrons and the
// wordmark set in a semibold grotesque. Generated by scripts/build-logo.py.
export const brandBlue = '#288ed6';
export const logoViewBox = '0 0 1720 422';
export const markViewBox = '0 0 419 422';
/** Blue square; the chevrons are cut out (even-odd). */
export const markPath = '{mark}';
export const chevronPath = '{poly(c1) + poly(c2)}';
export const wordPath = '{fw}{it}';
""")
